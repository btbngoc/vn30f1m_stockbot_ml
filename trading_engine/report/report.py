import json
import pandas as pd
from pathlib import Path


def generate_report():
    """Generate a simple HTML report linking analysis summary and chart.

    The report includes a summary table extracted from `analysis.csv` and
    embeds the chart generated by the visualization step (`chart.html`).
    The resulting file is written to `trading_engine/report/report.html`.
    """
    project_root = Path(__file__).resolve().parents[2]  # VN30F1M stock bot
    data_dir = project_root / "trading_engine" / "data"
    report_path = project_root / "trading_engine" / "report" / "report.html"

    # Load analysis summary (first row of CSV)
    analysis_csv = data_dir / "analysis.csv"
    summary_df = pd.read_csv(analysis_csv)
    summary = summary_df.iloc[0].to_dict()

    # Load dashboard JSON for additional info (optional)
    dashboard_json = data_dir / "dashboard.json"
    dashboard = {}
    if dashboard_json.exists():
        with open(dashboard_json, "r", encoding="utf-8") as f:
            dashboard = json.load(f)

    # Build HTML content
    html_parts = []
    html_parts.append("<!DOCTYPE html>")
    html_parts.append("<html lang='en'>")
    html_parts.append("<head>")
    html_parts.append("  <meta charset='UTF-8'>")
    html_parts.append("  <meta name='viewport' content='width=device-width, initial-scale=1.0'>")
    html_parts.append("  <title>VN30F1M Stock Bot Report</title>")
    html_parts.append("  <style>\n        body {font-family: 'Inter', sans-serif; background: #0f0f0f; color: #e0e0e0; margin:0; padding:2rem;}\n        h1 {font-size:2.5rem; color:#ffcc00; text-align:center;}\n        h2 {color:#ffcc00;}\n        table {width:100%; border-collapse:collapse; margin-top:1rem;}\n        th, td {padding:0.5rem; border:1px solid #444; text-align:left;}\n        th {background:#222;}\n        tr:nth-child(even) {background:#111;}\n        .chart {margin-top:2rem; display:flex; justify-content:center;}\n    </style>")
    html_parts.append("</head>")
    html_parts.append("<body>")
    html_parts.append("  <h1>VN30F1M Stock Bot Daily Report</h1>")
    html_parts.append("  <h2>Analysis Summary</h2>")
    html_parts.append("  <table>")
    html_parts.append("    <thead><tr><th>Metric</th><th>Value</th></tr></thead>")
    html_parts.append("    <tbody>")
    for key, value in summary.items():
        html_parts.append(f"      <tr><td>{key}</td><td>{value}</td></tr>")
    html_parts.append("    </tbody>")
    html_parts.append("  </table>")
    chart_path = project_root / "trading_engine" / "visualize" / "chart.html"
    if chart_path.exists():
        html_parts.append("  <div class='chart'>")
        html_parts.append(f"    <iframe src='{chart_path.as_posix()}' width='1000' height='600' style='border:none;'></iframe>")
        html_parts.append("  </div>")
    html_parts.append("</body>")
    html_parts.append("</html>")

    report_path.parent.mkdir(parents=True, exist_ok=True)
    with open(report_path, "w", encoding="utf-8") as f:
        f.write("\n".join(html_parts))
    print(f"Report generated at {report_path}")


def main():
    """Entry point for the report stage of the pipeline."""
    generate_report()

if __name__ == "__main__":
    main()
